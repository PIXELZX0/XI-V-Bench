LABEL_BASIS = {
    "easy": "정답이 본문에 명시되었거나 문장에 직접 서술됨; 추론 전 저작·검토됨",
    "standard": "명시적 평가 기준(루브릭), 추론 전 검토됨",
}


def build(tier, items):
    src = os.path.join(ROOT, "datasets", "en", f"{tier}.jsonl")
    dst = os.path.join(ROOT, "datasets", "ko", f"{tier}.jsonl")
    with open(src, encoding="utf-8") as fh:
        en = [json.loads(l) for l in fh if l.strip()]
    assert len(en) == 32, f"{tier}: en 문항 수 {len(en)}"
    assert len(items) == 32, f"{tier}: ko 문항 수 {len(items)}"

    out = []
    for i, (e, k) in enumerate(zip(en, items)):
        # 구조 필드 보존 검증
        assert e["question"]["type"] == ("score" if isinstance(k["criteria"], list) else
                                         ("noul" if e["question"]["type"] == "noul" else "choice")), i
        assert e["question"]["type"] == k.get("qtype", e["question"]["type"])
        assert len(e["labels"]) == len(k["labels"]), f"{tier}-{i}: 라벨 개수 불일치"
        # 정답 인덱스 동일성 검증
        e_idx = e["labels"].index(str(e["expected"])) if e["question"]["type"] == "score" \
            else e["labels"].index(e["expected"])
        k_idx = k["labels"].index(str(k["expected"])) if e["question"]["type"] == "score" \
            else k["labels"].index(k["expected"])
        assert e_idx == k_idx, f"{tier}-{i}: 정답 인덱스 불일치 {e_idx} != {k_idx}"

        item = {
            "id": f"ko-{tier}-{i:04d}",
            "family": e["family"],
            "group": e["group"],
            "state": k["state"],
            "question": {
                "criteria": k["criteria"],
                "instructions": k["instructions"],
                "type": e["question"]["type"],
            },
            "labels": k["labels"],
            "expected": k["expected"],
            "split": "public",
            "provenance": {
                "exclude_reason": None,
                "label_basis": LABEL_BASIS[tier],
                "license": e["provenance"]["license"],
                "source": e["provenance"]["source"] + " (XI-V localized)",
                "xi_lang": "ko",
                "xi_tier": tier,
                "source_kind": "localized",
                "source_item_id": e["provenance"]["source_item_id"],
                "origin_tier": e["provenance"]["origin_tier"],
                "translation_of": e["id"],
                "reviewed": False,
                "frozen_utc": FROZEN,
            },
            "difficulty_notes": e.get("difficulty_notes"),
        }
        out.append(item)

    os.makedirs(os.path.dirname(dst), exist_ok=True)
    with open(dst, "w", encoding="utf-8") as fh:
        for it in out:
            fh.write(json.dumps(it, ensure_ascii=False) + "\n")
    print(f"{dst}: {len(out)}문항")


if __name__ == "__main__":
    build("easy", EASY)
    build("standard", STANDARD)
